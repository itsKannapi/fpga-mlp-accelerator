#!/usr/bin/env bash
# ============================================================================
# run_sims.sh -- run every testbench with Icarus Verilog (no Vivado needed)
#
# For teammates on macOS/Linux (Vivado does not run on macOS), or anyone who
# wants a 10-second regression check before pushing. Works in Git Bash on
# Windows too.
#
#   Install Icarus:  macOS  brew install icarus-verilog
#                    Ubuntu sudo apt install iverilog
#   Run:             ./scripts/run_sims.sh          (from anywhere in the repo)
#
# Exits non-zero if any testbench fails, so it can gate a commit or CI job.
# ============================================================================
set -euo pipefail

REPO="$(cd "$(dirname "$0")/.." && pwd)"
BUILD="$REPO/vivado/icarus"            # vivado/ is git-ignored
mkdir -p "$BUILD"

# Same machine-specific header the Vivado script generates.
cat > "$BUILD/data_dir.vh" <<EOF
// Generated by scripts/run_sims.sh -- machine-specific, not committed.
\`ifndef DATA_DIR
\`define DATA_DIR "$REPO/rtl/"
\`endif
EOF

status=0
for tb in "$REPO"/sim/tb_*.v; do
    name="$(basename "$tb" .v)"
    printf '%-12s ' "$name"
    if ! iverilog -g2005 -I "$REPO/rtl" -I "$BUILD" -s "$name" \
            -o "$BUILD/$name.vvp" "$REPO"/src/*.v "$tb" 2> "$BUILD/$name.compile.log"; then
        echo "COMPILE ERROR (see vivado/icarus/$name.compile.log)"
        status=1
        continue
    fi
    vvp -n "$BUILD/$name.vvp" > "$BUILD/$name.log"
    if grep -q "ALL TESTS PASSED" "$BUILD/$name.log"; then
        grep "ALL TESTS PASSED" "$BUILD/$name.log"
    else
        echo "FAILED (see vivado/icarus/$name.log)"
        grep -m 5 -E "^FAIL" "$BUILD/$name.log" | sed 's/^/    /' || true
        status=1
    fi
done
exit $status
